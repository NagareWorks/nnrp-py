"""Shared NNRP enums."""

from enum import IntEnum, IntFlag


class PayloadKind(IntFlag):
    NONE = 0
    TENSOR = 0x00000001
    TOKEN_CHUNK = 0x00000002
    AUDIO_CHUNK = 0x00000004
    VIDEO_CHUNK = 0x00000008
    STRUCTURED_EVENT = 0x00000010
    TOOL_DELTA = 0x00000020
    OPAQUE_BYTES = 0x00000040


class WireFormat(IntEnum):
    CURRENT = 0


class MessageType(IntEnum):
    CLIENT_HELLO = 0x01
    SERVER_HELLO_ACK = 0x02
    SESSION_PATCH = 0x03
    SESSION_PATCH_ACK = 0x04
    CLOSE = 0x05
    ERROR = 0x06
    SESSION_OPEN = 0x07
    SESSION_OPEN_ACK = 0x08
    SESSION_CLOSE = 0x09
    SESSION_CLOSE_ACK = 0x0A
    FLOW_UPDATE = 0x17
    RESULT_HINT = 0x18
    TRANSPORT_PROBE = 0x19
    TRANSPORT_PROBE_ACK = 0x1A
    SESSION_MIGRATE = 0x1B
    SESSION_MIGRATE_ACK = 0x1C
    FRAME_SUBMIT = 0x10
    FRAME_CANCEL = 0x11
    RESULT_PUSH = 0x12
    RESULT_DROP = 0x13
    CACHE_PUT = 0x14
    CACHE_ACK = 0x15
    CACHE_INVALIDATE = 0x16
    PING = 0x20
    PONG = 0x21
    CANCEL = 0x30
    ABORT = 0x31
    PRIORITY_UPDATE = 0x32
    DEADLINE = 0x33
    EXPIRE_AT = 0x34
    SUPERSEDE = 0x35
    BUDGET_UPDATE = 0x36
    PROGRESS = 0x37
    PARTIAL_RESULT = 0x38
    BACKPRESSURE = 0x39
    CREDIT_UPDATE = 0x3A
    CAPABILITY_NEGOTIATION = 0x3B
    DEGRADE_PROFILE = 0x3C
    ROUTE_HINT = 0x3D
    EXECUTION_HINT = 0x3E
    TRACE_CONTEXT = 0x3F
    RESULT_DROP_REASON = 0x40
    OBJECT_DECLARE = 0x41
    OBJECT_REF = 0x42
    OBJECT_RELEASE = 0x43
    OBJECT_PATCH = 0x44
    OBJECT_DELTA = 0x45
    CACHE_REFERENCE = 0x46
    CACHE_MISS = 0x47
    ERROR_RECOVERABLE = 0x48
    RETRY_AFTER = 0x49


class HeaderFlags(IntFlag):
    NONE = 0
    ACK_REQUIRED = 0x00000001
    CAN_DROP = 0x00000002
    STALE = 0x00000004
    EOS = 0x00000008
    RETRANSMIT = 0x00000010
    KEYFRAME = 0x00000020


class FrameClass(IntEnum):
    KEYFRAME = 0
    DELTA = 1
    RETRANSMIT = 2
    DISCARDABLE = 3


class ErrorCode(IntEnum):
    UNSUPPORTED_VERSION = 0x0001
    AUTH_FAILED = 0x0002
    INVALID_STATE = 0x0003
    MALFORMED_HEADER = 0x0004
    MALFORMED_BODY = 0x0005
    UNSUPPORTED_CAPABILITY = 0x0006
    LIMIT_EXCEEDED = 0x0007
    FRAME_EXPIRED = 0x0008
    FRAME_CANCELLED = 0x0009
    CACHE_MISS = 0x000A
    SERVER_BUSY = 0x000B
    INTERNAL_ERROR = 0x000C
